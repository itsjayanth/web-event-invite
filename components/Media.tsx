'use client';
import { useEffect, useState } from 'react';
import type { MediaRef } from '@/content/wedding';
import { Placeholder } from './Placeholder';

interface Props {
  media: MediaRef;
  sizes: string;
  priority?: boolean;
  className?: string;
  /** CSS aspect ratio applied to the wrapper, e.g. "3 / 4". Omit if parent sizes it. */
  aspect?: string;
}

type BlurEntry = { lqip: string; width: number; height: number; widths: number[] };
type BlurMap = Record<string, BlurEntry>;

// blur.json (the LQIP base64 for every photo) is ~40 KB of data. Importing
// it directly would bundle all of it into every route's First Load JS. It
// is fetched once at runtime instead, from its public/ path, and shared by
// every <Media> instance via this module-level cache.
let blurPromise: Promise<BlurMap> | null = null;
function loadBlur(): Promise<BlurMap> {
  if (!blurPromise) {
    blurPromise = fetch('/media/blur.json')
      .then((r) => (r.ok ? r.json() : {}))
      .catch(() => ({}));
  }
  return blurPromise;
}

function useBlurEntry(base: string): BlurEntry | undefined {
  const [map, setMap] = useState<BlurMap | null>(null);
  useEffect(() => {
    let live = true;
    loadBlur().then((m) => live && setMap(m));
    return () => {
      live = false;
    };
  }, []);
  return map?.[base];
}

/** "/media/hero-couple.jpg" -> "hero-couple" */
function baseOf(src: string) {
  const file = src.split('/').pop() ?? src;
  return file.replace(/\.[^.]+$/, '');
}

function srcset(base: string, widths: number[], ext: 'avif' | 'webp' | 'jpg') {
  return widths.map((w) => `/media/${base}-${w}.${ext} ${w}w`).join(', ');
}

/**
 * Hand-written responsive <picture>: AVIF/WebP sources + a JPEG <img> fallback,
 * each with a real srcset generated by scripts/optimize-media.mjs. Falls back
 * to <Placeholder/> if the file is missing or fails to load — next/image is
 * not used because `output: 'export'` forces `images.unoptimized`, which
 * would otherwise ship the file verbatim with no resizing.
 */
export function Media({ media, sizes, priority, className = '', aspect }: Props) {
  const [failed, setFailed] = useState(false);
  const base = baseOf(media.src);
  const entry = useBlurEntry(base);
  const widths = entry?.widths ?? [480, 768, 1080, 1440];
  const fallbackSrc = `/media/${base}.jpg`;

  return (
    <div
      className={`relative overflow-hidden ${className}`}
      style={{
        ...(aspect ? { aspectRatio: aspect } : undefined),
        ...(entry ? { backgroundImage: `url(${entry.lqip})`, backgroundSize: 'cover', backgroundPosition: 'center' } : undefined),
      }}
    >
      <Placeholder caption={media.caption} className="absolute inset-0" />
      {!failed && (
        <picture>
          <source type="image/avif" srcSet={srcset(base, widths, 'avif')} sizes={sizes} />
          <source type="image/webp" srcSet={srcset(base, widths, 'webp')} sizes={sizes} />
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src={fallbackSrc}
            srcSet={srcset(base, widths, 'jpg')}
            sizes={sizes}
            alt={media.alt}
            width={entry?.width}
            height={entry?.height}
            loading={priority ? 'eager' : 'lazy'}
            decoding="async"
            fetchPriority={priority ? 'high' : undefined}
            className="absolute inset-0 h-full w-full object-cover"
            onError={() => {
              setFailed(true);
              if (process.env.NODE_ENV === 'development') console.warn(`[media] missing ${media.src}`);
            }}
          />
        </picture>
      )}
    </div>
  );
}
